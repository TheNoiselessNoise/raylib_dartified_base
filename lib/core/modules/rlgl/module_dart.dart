      final pixels = rl.Temp.Uint8$.Sized(size);

      _flat.rlCopyFramebuffer(
        x.toInt(),
        y.toInt(),
        width.toInt(),
        height.toInt(),
        format.value,
        pixels.cast(),
      );

      return pixels.asCopy(size);
    },
  );
  
